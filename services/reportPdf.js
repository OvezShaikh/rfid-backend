// services/reportPdf.js
const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');
const os = require('os');

const LOGO_PATH = path.join(__dirname, '..', 'assets', 'unostar-logo.png');

function fmtDate(d) {
  return new Date(d).toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' });
}

function renderReportPdf(agg) {
  const dir = path.join(os.tmpdir(), 'unostar-reports');
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  const filePath = path.join(dir, `report-${agg.period}-${agg.label}.pdf`);

  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 40, size: 'A4' });
    const stream = fs.createWriteStream(filePath);
    doc.pipe(stream);

    const brand = '#0a1929';
    const accent = '#0ea5e9';
    const contentW = doc.page.width - 80;

    // ── Header ──
    if (fs.existsSync(LOGO_PATH)) {
      try { doc.image(LOGO_PATH, 40, 30, { width: 60 }); } catch (_) {}
    }
    doc.font('Helvetica-Bold').fontSize(16).fillColor(brand)
      .text('Unostar Value Chain Pvt. Ltd.', 110, 35);
    doc.font('Helvetica').fontSize(9).fillColor('#555')
      .text('Plot no. PAP-67, Supa - Parner Industrial Park, Taluka - Parner, Dist.-Ahilyanagar', 110, 55);
    doc.moveTo(40, 85).lineTo(doc.page.width - 40, 85).lineWidth(2).strokeColor(brand).stroke();

    // ── Title ──
    const kind = agg.period === 'week' ? 'Weekly' : agg.period === 'month' ? 'Monthly' : 'Yearly';
    doc.y = 100;
    doc.font('Helvetica-Bold').fontSize(15).fillColor(brand)
      .text(`UnoTrace ${kind} Report`, { align: 'center' });
    doc.font('Helvetica').fontSize(11).fillColor('#333')
      .text(`Period: ${agg.label}   |   ${fmtDate(agg.start)} to ${fmtDate(agg.end)}`, { align: 'center' });
    doc.fontSize(9).fillColor('#777')
      .text(`Generated: ${agg.generatedAt.toLocaleString('en-IN')}`, { align: 'center' });
    doc.moveDown(1.2);

    // ── Summary box ──
    const boxY = doc.y;
    doc.rect(40, boxY, contentW, 95).fill('#f0f9ff');
    doc.fillColor(brand).font('Helvetica-Bold').fontSize(12).text('Summary', 55, boxY + 10);
    doc.font('Helvetica').fontSize(10).fillColor('#222');
    const stats = [
      ['Total Challans', agg.totals.challans],
      ['Sets Dispatched', agg.totals.sets],
      ['Components Moved', agg.totals.components],
      ['Exceptions Logged', agg.totals.exceptions],
      ['Sets Returned', agg.totals.returnedSets],
      ['Avg Turnaround', `${agg.totals.avgTurnaroundHours} hrs`],
    ];
    stats.forEach(([label, val], i) => {
      const col = i % 3, row = Math.floor(i / 3);
      const x = 55 + col * ((contentW - 30) / 3);
      const y = boxY + 32 + row * 30;
      doc.font('Helvetica-Bold').fontSize(13).fillColor(accent).text(String(val), x, y);
      doc.font('Helvetica').fontSize(8).fillColor('#555').text(label, x, y + 15);
    });
    doc.y = boxY + 105;

    // ── Component breakdown ──
    doc.font('Helvetica-Bold').fontSize(12).fillColor(brand).text('Component Breakdown');
    doc.moveDown(0.3);
    doc.font('Helvetica').fontSize(10).fillColor('#222');
    Object.entries(agg.components).forEach(([k, v]) => doc.text(`${k}:  ${v}`));
    doc.moveDown(1);

    // ── Daily breakdown ──
    if (agg.daily.length > 0) {
      doc.font('Helvetica-Bold').fontSize(12).fillColor(brand).text('Daily Breakdown');
      doc.moveDown(0.3);
      doc.font('Helvetica').fontSize(9).fillColor('#222');
      agg.daily.forEach((d) => {
        doc.text(`${fmtDate(d.day)}  —  ${d.challans} challan(s), ${d.sets_count} set(s)`);
      });
      doc.moveDown(1);
    }

    // ── Monthly rollup (only if year report) ──
    if (agg.period === 'year' && agg.monthly.length > 0) {
      doc.font('Helvetica-Bold').fontSize(12).fillColor(brand).text('Monthly Rollup');
      doc.moveDown(0.3);
      doc.font('Helvetica').fontSize(9).fillColor('#222');
      agg.monthly.forEach((m) => doc.text(`${m.month}  —  ${m.challans} challan(s)`));
      doc.moveDown(1);
    }

    // ── Itemized challans ──
    if (agg.challans.length > 0) {
      doc.font('Helvetica-Bold').fontSize(12).fillColor(brand).text('Challan Details');
      doc.moveDown(0.3);
      doc.font('Helvetica').fontSize(8).fillColor('#222');
      agg.challans.forEach((c) => {
        doc.text(
          `${c.challan_no}   |   ${fmtDate(c.created_at)}   |   ${c.from_name || '-'} → ${c.to_name || '-'}   |   ${c.total_sets || 0} set(s)`
        );
      });
    }

    // ── Footer ──
    doc.fontSize(8).fillColor('#999').text(
      `Generated by UnoTrace  |  ${agg.label}`,
      40, doc.page.height - 30, { align: 'center', width: contentW }
    );

    doc.end();
    stream.on('finish', () => resolve({ filePath, agg }));
    stream.on('error', reject);
  });
}

module.exports = { renderReportPdf };